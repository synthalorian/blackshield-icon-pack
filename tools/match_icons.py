def find_glyph(slug: str):
    n = norm(slug)
    # manual tables are keyed by human-readable names; normalize keys so
    # "discord_alt_2" matches slug "discord_alt_2" (n == "discordalt2")
    for table in (NMANUAL, NMANUAL_GENERIC, NMANUAL_REMAP):
        if n in table:
            src, name = table[n]
            lib = simple if src == "simple" else material
            if name in lib:
                return src, name, "manual"
    if n in sim_norm:
        return "simple", sim_norm[n], "exact"
    if n in mat_norm:
        return "material", mat_norm[n], "exact"
    # try stripping common suffixes
    for suf in ("app", "android", "mobile", "lite", "pro", "plus"):
        if n.endswith(suf) and n[: -len(suf)] in sim_norm:
            return "simple", sim_norm[n[: -len(suf)]], "suffix"
        if n.endswith(suf) and n[: -len(suf)] in mat_norm:
            return "material", mat_norm[n[: -len(suf)]], "suffix"
    # fuzzy — strict: near-identical AND one contains the other (a wrong
    # brand glyph is worse than a miss)
    cands = get_close_matches(n, sim_keys, n=1, cutoff=0.96)
    if cands and (n in cands[0] or cands[0] in n):
        return "simple", sim_norm[cands[0]], "fuzzy"
    cands = get_close_matches(n, mat_keys, n=1, cutoff=0.97)
    if cands and (n in cands[0] or cands[0] in n):
        return "material", mat_norm[cands[0]], "fuzzy"
    # brand-substring pass: slug contains a known brand (whatsapp_mods etc.)
    for b in SIM_BRANDS:
        if b in n:
            return "simple", sim_norm[b], "brand-sub"
    # letter-square app icons (letter_uppercase_square_a etc.) -> abc glyph
    if re.match(r"letter(uppercase|lowercase)?square[a-z0-9]$", n):
        return "material", "abc", "letter"
    # keyword pass (long tail -> generic glyph)
    for kw, (src, name) in KEYWORDS:
        if kw in n:
            lib = simple if src == "simple" else material
            if name in lib:
                return src, name, "keyword"
    # stage-1 token sweep leftovers
    for kw, (src, name) in KEYWORDS_TAIL:
        if kw in n:
            lib = simple if src == "simple" else material
            if name in lib:
                return src, name, "keyword"
    # final fallback: letter tile from the app's initial -> 100% coverage
    m0 = re.search(r"[a-z0-9]", n)
    if m0:
        return "letter", m0.group(0), "letter"
    return None

