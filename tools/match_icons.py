BASE = Path(__file__).resolve().parent / "lib"

# ---- parse arcticons appfilter ----
item_re = re.compile(r'component="ComponentInfo\{([^}]+)\}" drawable="([^"]+)"')
cov = defaultdict(list)  # slug -> [components]
for line in (BASE / "arcticons_appfilter.xml").read_text().splitlines():
    m = item_re.search(line)
    if m:
        cov[m.group(2)].append(m.group(1))

print(f"arcticons: {len(cov)} unique app slugs, {sum(len(v) for v in cov.values())} components")

# ---- glyph indexes ----
