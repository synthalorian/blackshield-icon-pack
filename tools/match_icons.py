"""Match Arcticons appfilter coverage to available glyphs.

Sources (all in /tmp/iconforge):
  - arcticons_appfilter.xml : component coverage data (factual data: package
    names / activities / app association). We take ONLY the component<->name
    mapping, never their artwork.
  - material/package/filled/*.svg : Material icons (Apache-2.0)
  - simple/package/icons/*.svg  : Simple Icons brand glyphs (CC0)

Outputs:
  - /tmp/iconforge/match_report.txt  : human-readable stats + misses
  - /tmp/iconforge/manifest.json     : {our_drawable: {glyph_src, glyph_name, components[]}}
"""
